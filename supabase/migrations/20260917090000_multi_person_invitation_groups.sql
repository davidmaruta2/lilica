-- ---------------------------------------------------------------------
-- 8. list_my_invitations(), redefined additively. A legacy (ungrouped)
--    pending invitation returns EXACTLY as before (one row,
--    careSpaceNames a single-element array). A grouped invitation
--    collapses ALL of its still-pending children into ONE row -- the
--    invitee experiences this as ONE invitation, per brief section 11.
-- ---------------------------------------------------------------------
drop function if exists public.list_my_invitations();

create function public.list_my_invitations()
returns table (
  id uuid,
  group_id uuid,
  care_space_id uuid,
  care_space_name text,
  care_space_names text[],
  invited_by_display_name text,
  role text,
  relationship_type text,
  relationship_label text,
  granted_domains text[],
  created_at timestamptz,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_email text;
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select lower(auth_user.email) into caller_email
  from auth.users auth_user
  where auth_user.id = (select auth.uid());
  if caller_email is null then
    return;
  end if;

  update public.care_space_invitations invitation
  set status = 'expired'
  where lower(invitation.invitee_email) = caller_email
    and invitation.status = 'pending'
    and invitation.expires_at <= now();

  -- Legacy, ungrouped rows -- unchanged behaviour.
  return query
  select
    invitation.id,
    null::uuid,
    invitation.care_space_id,
    coalesce(person.display_name, 'A Lilica care space'),
    array[coalesce(person.display_name, 'A Lilica care space')],
    coalesce(inviter_profile.display_name, 'The organiser'),
    invitation.role,
    invitation.relationship_type,
    invitation.relationship_label,
    invitation.granted_domains,
    invitation.created_at,
    invitation.expires_at
  from public.care_space_invitations invitation
  left join public.supported_people person on person.care_space_id = invitation.care_space_id
  left join public.care_space_memberships inviter_membership
    on inviter_membership.id = invitation.invited_by_membership_id
  left join public.profiles inviter_profile on inviter_profile.id = inviter_membership.user_id
  where lower(invitation.invitee_email) = caller_email
    and invitation.status = 'pending'
    and invitation.invitation_group_id is null

  union all

  -- Grouped rows -- one row per group, aggregating every still-pending
  -- child's own supported-person name. Role/domains are identical
  -- across every child of a group by construction (brief sections
  -- 13/14), so a representative child's values are exact for the whole
  -- group.
  select
    representative.id,
    grp.id,
    representative.care_space_id,
    coalesce(names.first_name, 'A Lilica care space'),
    coalesce(names.all_names, '{}'),
    coalesce(inviter_profile.display_name, 'The organiser'),
    representative.role,
    representative.relationship_type,
    representative.relationship_label,
    representative.granted_domains,
    grp.created_at,
    representative.expires_at
  from public.care_space_invitation_groups grp
  join lateral (
    select ci.* from public.care_space_invitations ci
    where ci.invitation_group_id = grp.id and ci.status = 'pending'
    order by ci.created_at
    limit 1
  ) representative on true
  join lateral (
    -- Ordered by name, not created_at -- see resolve_invitation_by_code()'s
    -- matching comment: same-call sibling rows can tie on
    -- statement_timestamp(), so alphabetical is the deterministic choice.
    select
      array_agg(coalesce(sp.display_name, 'A Lilica care space') order by sp.display_name) as all_names,
      (array_agg(coalesce(sp.display_name, 'A Lilica care space') order by sp.display_name))[1] as first_name
    from public.care_space_invitations ci
    join public.supported_people sp on sp.care_space_id = ci.care_space_id
    where ci.invitation_group_id = grp.id and ci.status = 'pending'
  ) names on true
  left join public.care_space_memberships inviter_membership
    on inviter_membership.id = representative.invited_by_membership_id
  left join public.profiles inviter_profile on inviter_profile.id = inviter_membership.user_id
  where lower(grp.invitee_email) = caller_email
    and grp.status = 'pending'

  order by created_at desc;
end;
$$;

revoke all on function public.list_my_invitations() from public;
revoke all on function public.list_my_invitations() from anon;
grant execute on function public.list_my_invitations() to authenticated;

-- ---------------------------------------------------------------------
-- 9. list_care_space_invitations(), redefined additively. Still scoped
--    to ONE care space (an organiser viewing Maggie's Care Circle sees
--    exactly Maggie's own row) -- but a grouped row's delivery state
--    and group_participant_names now come from the shared GROUP,
--    coherently, never per-child (brief section 23).
-- ---------------------------------------------------------------------
drop function if exists public.list_care_space_invitations(uuid);

create function public.list_care_space_invitations(target_care_space_id uuid)
returns table (
  id uuid,
  invitee_email text,
  role text,
  relationship_type text,
  relationship_label text,
  granted_domains text[],
  status text,
  invite_code text,
  group_id uuid,
  group_participant_names text[],
  last_email_sent_at timestamptz,
  email_send_count integer,
  last_share_opened_at timestamptz,
  created_at timestamptz,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.care_space_memberships membership
    where membership.care_space_id = target_care_space_id
      and membership.user_id = (select auth.uid())
      and membership.role = 'organiser'
      and membership.membership_status = 'active'
  ) then
    raise exception 'Only an active organiser can view invitations' using errcode = '42501';
  end if;

  return query
  select
    invitation.id, invitation.invitee_email, invitation.role,
    invitation.relationship_type, invitation.relationship_label,
    invitation.granted_domains, invitation.status,
    -- The GROUP's own invite_code for a grouped row, never the child's
    -- own internal one -- the child's invite_code column still exists
    -- (invite_member()'s own NOT NULL default fires regardless) but is
    -- never shown to a user: sharing it instead of the group's code
    -- would silently resolve to a single-person preview missing
    -- everyone else in the group, defeating the whole feature.
    coalesce(grp.invite_code, invitation.invite_code),
    invitation.invitation_group_id,
    case when invitation.invitation_group_id is not null then
      (select array_agg(coalesce(sp.display_name, 'A Lilica care space') order by sp.display_name)
       from public.care_space_invitations ci
       join public.supported_people sp on sp.care_space_id = ci.care_space_id
       where ci.invitation_group_id = invitation.invitation_group_id)
    else null end,
    coalesce(grp.last_email_sent_at, invitation.last_email_sent_at),
    coalesce(grp.email_send_count, invitation.email_send_count),
    coalesce(grp.last_share_opened_at, invitation.last_share_opened_at),
    invitation.created_at, invitation.expires_at
  from public.care_space_invitations invitation
  left join public.care_space_invitation_groups grp on grp.id = invitation.invitation_group_id
  where invitation.care_space_id = target_care_space_id
  order by invitation.created_at desc;
end;
$$;

revoke all on function public.list_care_space_invitations(uuid) from public;
revoke all on function public.list_care_space_invitations(uuid) from anon;
grant execute on function public.list_care_space_invitations(uuid) to authenticated;

