-- ---------------------------------------------------------------------
-- 3. Group code generator -- same alphabet/length/shape as
--    generate_invitation_code(), but checked against BOTH tables so a
--    group code and a (never user-facing) legacy invitation code can
--    never collide, even though only one of the two namespaces is ever
--    shown to a user.
-- ---------------------------------------------------------------------
create function public.generate_invitation_group_code()
returns text
language plpgsql
set search_path = ''
as $$
declare
  alphabet text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  candidate text;
  attempt int := 0;
begin
  loop
    candidate := '';
    for i in 1..8 loop
      candidate := candidate || substr(alphabet, (floor(random() * length(alphabet)) + 1)::int, 1);
    end loop;
    attempt := attempt + 1;
    exit when not exists (
      select 1 from public.care_space_invitation_groups where invite_code = candidate
    ) and not exists (
      select 1 from public.care_space_invitations where invite_code = candidate
    );
    if attempt > 20 then
      raise exception 'Could not generate a unique invitation code' using errcode = '55000';
    end if;
  end loop;
  return candidate;
end;
$$;

-- ---------------------------------------------------------------------
-- 4. invite_member_group(): the one new organiser-facing entry point.
--    Orchestrates the EXISTING invite_member() once per selected care
--    space -- see the migration header for the full reasoning.
-- ---------------------------------------------------------------------
create function public.invite_member_group(
  target_care_space_ids uuid[],
  invitee_email_input text,
  member_role text,
  granted_domains text[],
  member_relationship_type text,
  member_relationship_label text,
  operation_id uuid
)
returns table (
  group_id uuid,
  invite_code text,
  care_space_id uuid,
  supported_person_name text,
  outcome text,
  -- One representative child invitation id, for the client's join link
  -- (which needs SOME real invitation id to build lilica://invite/<id>
  -- -- functionally only ever a deep-link trigger, never a lookup key,
  -- but a real id is safer/less surprising than a placeholder).
  representative_invitation_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := auth.uid();
  existing_group_id uuid;
  resolved_group_id uuid;
  resolved_code text;
  target_id uuid;
  child_invitation public.care_space_invitations%rowtype;
  distinct_count integer;
  any_invited boolean := false;
begin
  if caller_id is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if target_care_space_ids is null or array_length(target_care_space_ids, 1) is null then
    raise exception 'Select at least one supported person' using errcode = '22023';
  end if;

  select count(distinct value) into distinct_count from unnest(target_care_space_ids) as value;
  if distinct_count <> array_length(target_care_space_ids, 1) then
    raise exception 'The same supported person was selected more than once' using errcode = '22023';
  end if;

  -- Idempotency, mirroring invite_member()'s own operation_id pattern --
  -- a retried client call with the same operation_id returns the same
  -- already-created group rather than creating a second one.
  select ig.id into existing_group_id
  from public.care_space_invitation_groups ig
  where ig.operation_id = invite_member_group.operation_id;

  if existing_group_id is not null then
    resolved_group_id := existing_group_id;
    select ig.invite_code into resolved_code from public.care_space_invitation_groups ig where ig.id = resolved_group_id;
  else
    resolved_code := public.generate_invitation_group_code();
    insert into public.care_space_invitation_groups (
      invited_by_user_id, invitee_email, role, relationship_type, relationship_label,
      invite_code, operation_id
    ) values (
      caller_id, lower(trim(invitee_email_input)), member_role, member_relationship_type, member_relationship_label,
      resolved_code, invite_member_group.operation_id
    )
    returning id into resolved_group_id;
  end if;

  foreach target_id in array target_care_space_ids loop
    begin
      -- Reuses invite_member() completely unmodified -- identical
      -- authority check (only an active organiser of THIS specific
      -- care space may invite for it -- brief section 29), identical
      -- validation, identical idempotent upsert-while-pending
      -- behaviour, identical "already has access" rejection (brief
      -- sections 35/36).
      child_invitation := public.invite_member(
        target_id, invitee_email_input, member_role, granted_domains,
        member_relationship_type, member_relationship_label, gen_random_uuid()
      );
      update public.care_space_invitations
      set invitation_group_id = resolved_group_id
      where id = child_invitation.id;
      any_invited := true;

      group_id := resolved_group_id;
      invite_code := resolved_code;
      care_space_id := target_id;
      select sp.display_name into supported_person_name from public.supported_people sp where sp.care_space_id = target_id;
      outcome := 'invited';
      representative_invitation_id := child_invitation.id;
      return next;
    exception
      when others then
        if sqlerrm = 'This person already has access to this care space' then
          group_id := resolved_group_id;
          invite_code := resolved_code;
          care_space_id := target_id;
          select sp.display_name into supported_person_name from public.supported_people sp where sp.care_space_id = target_id;
          outcome := 'already_has_access';
          representative_invitation_id := null;
          return next;
        else
          -- Any OTHER failure (wrong authority, invalid role, invalid
          -- email, etc.) aborts the ENTIRE call -- Postgres rolls back
          -- everything this call did, including the group row itself,
          -- so nothing partial is ever left behind (brief section 29:
          -- "server must reject unauthorised care-space inclusion").
          raise;
        end if;
    end;
  end loop;

  -- Nothing was actually invited (every selected person already has
  -- access) -- remove the now-pointless empty group rather than
  -- leaving an orphan row with zero children.
  if not any_invited then
    delete from public.care_space_invitation_groups where id = resolved_group_id;
    group_id := null;
    invite_code := null;
  end if;
end;
$$;

revoke all on function public.invite_member_group(uuid[], text, text, text[], text, text, uuid) from public;
revoke all on function public.invite_member_group(uuid[], text, text, text[], text, text, uuid) from anon;
grant execute on function public.invite_member_group(uuid[], text, text, text[], text, text, uuid) to authenticated;

-- ---------------------------------------------------------------------
-- 5. resolve_invitation_by_code(), redefined additively. The
--    authentication/rate-limit/threshold logic below is copied
--    VERBATIM from 20260916170000_invitation_code_rate_limit_bypass_
--    fix.sql -- completely preserved, not reworked -- with exactly one
--    addition: after normalising the code, it now checks
--    care_space_invitation_groups FIRST. A legacy invitation's own
--    invite_code and a group's invite_code can never collide (enforced
--    by generate_invitation_group_code() checking both tables), so
--    there is no ambiguity in trying the group table first.
-- ---------------------------------------------------------------------
drop function if exists public.resolve_invitation_by_code(text);

create function public.resolve_invitation_by_code(code_input text)
returns table (
  result_status text,
  id uuid,
  group_id uuid,
  care_space_name text,
  care_space_names text[],
  invited_by_display_name text,
  role text,
  granted_domains text[]
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  window_seconds constant int := 300;
  max_attempts constant int := 10;
  existing_attempt public.invitation_code_attempts%rowtype;
  throttled boolean := false;
  normalised_code text;
  invitation public.care_space_invitations%rowtype;
  found_group public.care_space_invitation_groups%rowtype;
  person_name text;
  inviter_name text;
  person_names text[];
  representative_invitation public.care_space_invitations%rowtype;
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  -- Rate-limit accounting -- UNCHANGED from the security-correction
  -- migration. Preserved verbatim: unconditional, before any lookup,
  -- and every business-level outcome below is RETURNED, never RAISEd,
  -- so nothing here is ever rolled back.
  select * into existing_attempt
  from public.invitation_code_attempts
  where user_id = (select auth.uid())
  for update;

  if not found then
    insert into public.invitation_code_attempts (user_id, window_start, attempt_count)
    values ((select auth.uid()), now(), 1);
  elsif existing_attempt.window_start <= now() - (window_seconds || ' seconds')::interval then
    update public.invitation_code_attempts
    set window_start = now(), attempt_count = 1
    where user_id = (select auth.uid());
  elsif existing_attempt.attempt_count >= max_attempts then
    throttled := true;
  else
    update public.invitation_code_attempts
    set attempt_count = attempt_count + 1
    where user_id = (select auth.uid());
  end if;

  if throttled then
    return query select 'throttled'::text, null::uuid, null::uuid, null::text, null::text[], null::text, null::text, null::text[];
    return;
  end if;

  normalised_code := upper(regexp_replace(coalesce(code_input, ''), '[^A-Za-z0-9]', '', 'g'));
  if normalised_code = '' then
    return query select 'invalid_input'::text, null::uuid, null::uuid, null::text, null::text[], null::text, null::text, null::text[];
    return;
  end if;

  -- Lazy expiry -- legacy single-person path, unchanged.
  update public.care_space_invitations inv
  set status = 'expired'
  where inv.invite_code = normalised_code
    and inv.status = 'pending'
    and inv.expires_at <= now();

  -- 5a. Try the GROUP table first.
  select * into found_group
  from public.care_space_invitation_groups
  where invite_code = normalised_code;

  if found then
    -- Lazy expiry for every child of this group -- the legacy sweep
    -- above only matches a row by its OWN (never user-facing)
    -- invite_code, which never equals the group's own code, so a
    -- group's children need their own explicit sweep here.
    update public.care_space_invitations child
    set status = 'expired'
    where child.invitation_group_id = found_group.id
      and child.status = 'pending'
      and child.expires_at <= now();

    -- Lazy group expiry -- coherent: if every pending child of this
    -- group has independently expired (each child's own expires_at
    -- comes from invite_member()'s own default/refresh logic, and every
    -- child was created/refreshed together in the same
    -- invite_member_group() call, so they share the same expiry), mark
    -- the group expired too rather than leaving it "pending" with
    -- nothing left to accept.
    if found_group.status = 'pending' and not exists (
      select 1 from public.care_space_invitations child
      where child.invitation_group_id = found_group.id and child.status = 'pending'
    ) then
      update public.care_space_invitation_groups grp set status = 'expired' where grp.id = found_group.id;
      found_group.status := 'expired';
    end if;

    if found_group.status <> 'pending' then
      return query select 'inactive'::text, null::uuid, null::uuid, null::text, null::text[], null::text, null::text, null::text[];
      return;
    end if;

    -- Ordered by name, not created_at -- every child of a group is
    -- created in the SAME invite_member_group() call, so their
    -- statement_timestamp()-derived created_at values can tie, which
    -- would make a created_at ordering non-deterministic. Alphabetical
    -- is both stable and a sensible display order.
    select array_agg(coalesce(sp.display_name, 'a Lilica care space') order by sp.display_name)
      into person_names
    from public.care_space_invitations ci
    join public.supported_people sp on sp.care_space_id = ci.care_space_id
    where ci.invitation_group_id = found_group.id and ci.status = 'pending';

    select * into representative_invitation
    from public.care_space_invitations
    where invitation_group_id = found_group.id and status = 'pending'
    order by created_at
    limit 1;

    select profile.display_name into inviter_name
    from public.care_space_memberships membership
    join public.profiles profile on profile.id = membership.user_id
    where membership.id = representative_invitation.invited_by_membership_id;

    return query
    select
      'ok'::text,
      representative_invitation.id,
      found_group.id,
      coalesce(person_names[1], 'a Lilica care space'),
      coalesce(person_names, '{}'),
      coalesce(inviter_name, 'The organiser'),
      representative_invitation.role,
      representative_invitation.granted_domains;
    return;
  end if;

  -- 5b. Legacy single-person path -- completely unchanged behaviour.
  select * into invitation
  from public.care_space_invitations
  where invite_code = normalised_code;

  if not found then
    return query select 'not_found'::text, null::uuid, null::uuid, null::text, null::text[], null::text, null::text, null::text[];
    return;
  end if;

  if invitation.status <> 'pending' then
    return query select 'inactive'::text, null::uuid, null::uuid, null::text, null::text[], null::text, null::text, null::text[];
    return;
  end if;

  select display_name into person_name
  from public.supported_people
  where care_space_id = invitation.care_space_id;

  select profile.display_name into inviter_name
  from public.care_space_memberships membership
  join public.profiles profile on profile.id = membership.user_id
  where membership.id = invitation.invited_by_membership_id;

  return query
  select
    'ok'::text,
    invitation.id,
    null::uuid,
    coalesce(person_name, 'a Lilica care space'),
    array[coalesce(person_name, 'a Lilica care space')],
    coalesce(inviter_name, 'The organiser'),
    invitation.role,
    invitation.granted_domains;
end;
$$;

revoke all on function public.resolve_invitation_by_code(text) from public;
revoke all on function public.resolve_invitation_by_code(text) from anon;
grant execute on function public.resolve_invitation_by_code(text) to authenticated;

-- ---------------------------------------------------------------------
-- 6. accept_invitation_group() / decline_invitation_group() /
--    revoke_invitation_group(): orchestrate the EXISTING accept_
--    invitation()/decline_invitation()/revoke_invitation() over every
--    still-pending child. None of these three catches an exception, so
--    Postgres's own transactional rollback makes each one naturally
--    atomic -- brief section 12's "all succeed or fail coherently,
--    never partial" requirement, with zero new transaction-control
--    code and zero duplicated membership/permission logic.
-- ---------------------------------------------------------------------
create function public.accept_invitation_group(target_group_id uuid, operation_id uuid)
returns uuid[]
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_email text;
  found_group public.care_space_invitation_groups%rowtype;
  child_id uuid;
  new_membership_id uuid;
  membership_ids uuid[] := '{}'::uuid[];
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select lower(email) into caller_email from auth.users where id = (select auth.uid());

  select * into found_group
  from public.care_space_invitation_groups
  where id = target_group_id
  for update;

  if not found or caller_email is null or lower(found_group.invitee_email) <> caller_email then
    raise exception 'Invitation not found' using errcode = '42501';
  end if;

  if found_group.status <> 'pending' then
    raise exception 'This invitation is no longer open' using errcode = '22023';
  end if;

  for child_id in
    select id from public.care_space_invitations
    where invitation_group_id = target_group_id and status = 'pending'
    order by created_at
  loop
    -- accept_invitation() itself derives a fresh, distinct membership id
    -- for a brand-new membership (its own gen_random_uuid()-equivalent
    -- via the passed operation_id) -- a distinct operation_id per child
    -- is required since care_space_memberships.id must be unique
    -- per-row; reusing the SAME id across children would collide.
    new_membership_id := public.accept_invitation(child_id, gen_random_uuid());
    membership_ids := membership_ids || new_membership_id;
  end loop;

  if array_length(membership_ids, 1) is null then
    -- Every child had already left the pending state some other way
    -- (e.g. independently revoked one-by-one) by the time this ran.
    raise exception 'This invitation is no longer open' using errcode = '22023';
  end if;

  update public.care_space_invitation_groups
  set status = 'accepted', responded_at = now()
  where id = target_group_id;

  return membership_ids;
end;
$$;

revoke all on function public.accept_invitation_group(uuid, uuid) from public;
revoke all on function public.accept_invitation_group(uuid, uuid) from anon;
grant execute on function public.accept_invitation_group(uuid, uuid) to authenticated;

create function public.decline_invitation_group(target_group_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_email text;
  found_group public.care_space_invitation_groups%rowtype;
  child_id uuid;
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select lower(email) into caller_email from auth.users where id = (select auth.uid());

  select * into found_group
  from public.care_space_invitation_groups
  where id = target_group_id
  for update;

  if not found or caller_email is null or lower(found_group.invitee_email) <> caller_email then
    raise exception 'Invitation not found' using errcode = '42501';
  end if;

  if found_group.status <> 'pending' then
    raise exception 'This invitation is no longer open' using errcode = '22023';
  end if;

  for child_id in
    select id from public.care_space_invitations
    where invitation_group_id = target_group_id and status = 'pending'
  loop
    perform public.decline_invitation(child_id);
  end loop;

  update public.care_space_invitation_groups
  set status = 'declined', responded_at = now()
  where id = target_group_id;
end;
$$;

