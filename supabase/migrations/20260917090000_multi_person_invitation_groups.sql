-- LILICA -- MULTI-PERSON CARE CIRCLE INVITATION SCOPE (`\downloads\perm.txt`,
-- 15 September 2026).
--
-- REAL BUG THIS FIXES: davidmaruta2@gmail.com supports both Maggie and
-- Ben. He invited dtm35@cam.ac.uk once; dtm35 could see Maggie but not
-- Ben. Root cause (confirmed by inspecting the actual schema, not
-- inferred from UI labels): a care_space is exactly one supported
-- person (supported_people.care_space_id is UNIQUE); a membership is
-- exactly one (user, care_space) pair; and care_space_invitations.
-- care_space_id is a single not-null column -- ALL THREE are, and
-- remain, genuinely single-care-space primitives. invite_member()
-- therefore only ever created ONE invitation, scoped to Maggie's care
-- space alone -- Ben was simply never invited. This was not a bug in
-- accept_invitation()/RLS/domain grants; it was a missing UI/orchestration
-- capability: nothing let David select MULTIPLE supported people for one
-- invitation.
--
-- ARCHITECTURE CHOSEN (brief section 8, option A): a lightweight
-- "invitation bundle" that ORCHESTRATES the existing, completely
-- unmodified per-care-space primitives -- it does not replace them.
--   * care_space_invitation_groups: one row per organiser-facing
--     invitation ACTION covering 1+ explicitly-selected supported
--     people. Carries the ONE human-friendly invite_code and the ONE
--     set of server-authoritative delivery-state columns the invitee/
--     organiser actually experiences as "one invitation".
--   * care_space_invitations gains one additive, nullable
--     invitation_group_id column. NULL means "an ordinary,
--     ungrouped legacy invitation" -- its behaviour is completely
--     unchanged. Non-null means "one of this group's children" -- it
--     is still a real, independently-authoritative row: its own
--     care_space_id, its own role/domain grants, its own status. Its
--     own invite_code column is untouched (still NOT NULL, still
--     unique, still generated by generate_invitation_code()) but is
--     simply never shown to the user for a grouped invitation -- the
--     group's own invite_code is the one human-friendly code that
--     resolves the whole bundle.
--   * invite_member_group() creates/extends a group by calling the
--     EXISTING invite_member() once per selected care space (not a
--     reimplementation) -- so every authority check, idempotency
--     rule, and "this person already has access" rule invite_member()
--     already enforces applies IDENTICALLY per selected care space,
--     with zero duplicated logic. A care space where the invitee
--     already has active access is skipped (reported back as
--     'already_has_access', per brief sections 35/36) rather than
--     erroring the whole call; any OTHER failure (most importantly,
--     the organiser not actually being an active organiser of one of
--     the selected care spaces -- brief section 29) aborts the ENTIRE
--     call, and Postgres's own transactional rollback means nothing
--     partial is ever left behind.
--   * accept_invitation_group()/decline_invitation_group()/
--     revoke_invitation_group() each loop over the group's own pending
--     children calling the EXISTING accept_invitation()/
--     decline_invitation()/revoke_invitation() -- again, zero
--     duplicated membership/permission logic. Because none of these
--     three ever explicitly catches an exception, an uncaught failure
--     partway through rolls back EVERY child processed earlier in the
--     SAME call (natural Postgres transactional semantics) -- so
--     "Maggie accepted, Ben failed" can never be left half-done.
--   * resolve_invitation_by_code() (the already-corrected, single-
--     RPC, rate-limited resolver from
--     20260916170000_invitation_code_rate_limit_bypass_fix.sql) is
--     redefined ADDITIVELY: its authentication/rate-limit/threshold
--     logic is completely UNTOUCHED (preserved verbatim); it now also
--     checks care_space_invitation_groups.invite_code FIRST (a group
--     code can never collide with a legacy invitation's own internal
--     code -- see generate_invitation_group_code() below), and returns
--     every selected person's name plus a group_id the client uses to
--     call accept_invitation_group() instead of accept_invitation().
--   * list_my_invitations() and list_care_space_invitations() are
--     redefined additively to surface a group's full people list and
--     its own coherent delivery state, while every legacy, ungrouped
--     row continues to behave exactly as before.
--
-- WHAT THIS DOES NOT DO (brief sections 2/26/38, explicitly): no
-- global/account-wide Care Circle; no membership that spans more than
-- one care space; no rewrite of accept_invitation()/care_space_
-- memberships; no automatic access to a supported person added later;
-- Jackie (or anyone else not explicitly selected) never gains any
-- access, membership or visibility from this migration.

-- ---------------------------------------------------------------------
-- 1. The group table itself.
-- ---------------------------------------------------------------------
create table public.care_space_invitation_groups (
  id uuid primary key default gen_random_uuid(),
  invited_by_user_id uuid not null references auth.users(id) on delete restrict,
  invitee_email text not null,
  role text not null check (role in ('contributor', 'viewer')),
  relationship_type text not null default 'Someone else' check (
    relationship_type in ('Mum', 'Dad', 'Partner', 'Child', 'Grandparent', 'Other relative', 'Someone else')
  ),
  relationship_label text,
  constraint care_space_invitation_groups_relationship_label check (
    case
      when relationship_type in ('Other relative', 'Someone else')
        then char_length(btrim(relationship_label)) between 1 and 50
      else relationship_label is null
    end
  ),
  invite_code text not null unique,
  constraint care_space_invitation_groups_invite_code_shape
    check (invite_code ~ '^[A-Z2-9]{8}$'),
  status text not null default 'pending' check (
    status in ('pending', 'accepted', 'declined', 'expired', 'revoked')
  ),
  operation_id uuid not null unique,
  created_at timestamptz not null default statement_timestamp(),
  responded_at timestamptz,
  -- Server-authoritative delivery state, at the GROUP level -- brief
  -- section 23: "the organiser sent ONE invitation to one human." One
  -- email/Share action for the whole group, never a per-child fan-out.
  last_email_sent_at timestamptz,
  email_send_count integer not null default 0,
  last_share_opened_at timestamptz
);

