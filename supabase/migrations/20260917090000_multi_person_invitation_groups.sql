create function public.revoke_invitation_group(target_group_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  found_group public.care_space_invitation_groups%rowtype;
  child_id uuid;
  revoked_any boolean := false;
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select * into found_group
  from public.care_space_invitation_groups
  where id = target_group_id
  for update;

  if not found then
    raise exception 'Invitation not found' using errcode = '42501';
  end if;

  if found_group.status <> 'pending' then
    raise exception 'This invitation is no longer open' using errcode = '22023';
  end if;

  -- revoke_invitation() itself enforces "only an active organiser of
  -- THIS child's own care space" per child -- if the caller organises
  -- some but not all of the group's care spaces, this fails (and rolls
  -- back) rather than partially revoking, which is the same coherent-
  -- or-nothing guarantee brief section 19 asks for.
  for child_id in
    select id from public.care_space_invitations
    where invitation_group_id = target_group_id and status = 'pending'
  loop
    perform public.revoke_invitation(child_id);
    revoked_any := true;
  end loop;

  if not revoked_any then
    raise exception 'This invitation is no longer open' using errcode = '22023';
  end if;

  update public.care_space_invitation_groups
  set status = 'revoked', responded_at = now()
  where id = target_group_id;
end;
$$;

revoke all on function public.revoke_invitation_group(uuid) from public;
revoke all on function public.revoke_invitation_group(uuid) from anon;
grant execute on function public.revoke_invitation_group(uuid) to authenticated;

